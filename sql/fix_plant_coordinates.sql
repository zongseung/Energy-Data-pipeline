-- 2-1. 신인천빛드림본부 부속 태양광 6기  [리뷰 반영: POI 기반으로 정밀화]
--   근거: OSM POI "신인천복합화력발전소"(청라3동, 서구) = 37.5359/126.6085.
--   1차 판정은 주소 도로명("장도로") 기준점(37.5464/126.6059, 1.2km 오차)이었다.
UPDATE plants SET lat = 37.5359, lon = 126.6085
WHERE plant_id IN (9, 8, 1, 12, 10, 13);
--   9  = 한국남부발전(주)_신인천해수구취수구 태양광발전실적
--   8  = 한국남부발전(주)_신인천전망대 태양광발전실적
--   1  = 한국남부발전(주)_신인천소내 태양광발전실적
--   12 = 한국남부발전(주)_신인천 북측부지 태양광발전실적
--   10 = 한국남부발전(주)_신인천 주차장 태양광발전실적
--   13 = 한국남부발전(주)_신인천 1, 2단계 주차장 태양광발전실적

-- 2-2. 부산빛드림본부 부속 태양광 5기  [리뷰 반영: Important 3 — 후보점 재확인]
--   1차 판정은 "감천항로" 지오코딩 후보 3점(35.05~35.09) 중 첫 결과를 그냥 채택한
--   것이라 리뷰에서 위험으로 지목됐다(최근접 ASOS는 다행히 안 바뀜). 행정동
--   "구평동"(감천항로 7이 속한 동) 중심점으로 방법을 바꿔 재확정: 35.0716/128.9903.
UPDATE plants SET lat = 35.0716, lon = 128.9903
WHERE plant_id IN (5, 6, 7, 14, 15);
--   5  = 한국남부발전(주)_부산복합자재창고 태양광발전실적
--   6  = 한국남부발전(주)_부산수처리장 태양광발전실적
--   7  = 한국남부발전(주)_부산운동장 태양광발전실적
--   14 = 한국남부발전(주)_부산본부 태양광발전실적 (1호기)
--   15 = 한국남부발전(주)_부산본부 태양광발전실적 (2호기)

-- 2-3. 남제주빛드림본부 부속 태양광 1기  [리뷰 반영: POI 기반으로 정밀화]
--   근거: OSM POI "남제주화력발전소"(화순리, 안덕면) = 33.2371/126.3417.
UPDATE plants SET lat = 33.2371, lon = 126.3417 WHERE plant_id = 3;
--   3 = 한국남부발전(주)_남제주소내 태양광발전실적

-- 2-4. 삼척빛드림본부 부속 태양광 3기  [리뷰 반영: Important 3 — 11.7km 오차 수정]
--   1차 판정(37.2728/129.3229)은 "삼척로" 지오코딩 후보 중 하나를 그대로 썼는데,
--   그 지점은 실제로 도로명주소 "원덕읍" 북쪽 구간(원덕읍·근덕면 경계 인근)이었다.
--   실제 삼척빛드림본부 부지는 원덕읍 **호산리**(호산항~작진항 해안, 삼척LNG기지
--   인접)에 있다. 호산리 행정중심(37.1840/129.3330)과, "삼척로" 지오코딩 후보 중
--   원덕읍 남쪽 구간(37.1700/129.3391)이 모두 이 부근에 모여 있어 교차검증됨 —
--   37.1750/129.3400 채택.
--   최근접 ASOS: 1차 판정값은 동해(106) 31.4km로 오판정, 재조사값은 울진(130)
--   21.4km로 실제 최근접 관측소가 바뀐다.
UPDATE plants SET lat = 37.1750, lon = 129.3400
WHERE plant_id IN (18, 16, 17);
--   18 = 한국남부발전(주)_삼척소내 태양광발전실적 (3호기)
--   16 = 한국남부발전(주)_삼척소내 태양광발전실적 (1호기)
--   17 = 한국남부발전(주)_삼척소내 태양광발전실적 (2호기)

-- 2-5. 한국농어촌공사 영암태양광 3기
--   근거: 디지털영암문화대전 "전남 영암군 삼호읍 용앙리" 간척지(2008년 준공, 3,000kW).
--   신뢰도: 근사 — 읍 단위 중심, "영암1차/영암2차"가 이 사업의 1·2단계인지는
--   문헌상 완전히 확인되지 않음(§5 참고). 셋 다 동일 좌표로 채움.
--   주의: plant_id=140(영암태양광_합계)은 141/142와 물리적으로 같은 부지를 가리키는
--   집계행일 가능성이 높다. Task 3 뷰에서 발전소 단위로 조인·합산할 때 140을 141/142와
--   함께 넣으면 발전량이 중복 계상될 수 있다 — Task 3에서 141/142만 실측 plant로 쓰고
--   140은 제외하는 것을 권장(§5 각주).
UPDATE plants SET lat = 34.7458, lon = 126.4694
WHERE plant_id IN (140, 141, 142);
--   140 = 영암태양광_합계  ← Task 3 조인 시 이중계상 위험, 위 주의 참고
--   141 = 영암1차태양광
--   142 = 영암2차태양광

-- 2-6. 율치태양광 (plant_id=143) — 미확정, 의도적으로 UPDATE 없음.
--   웹 조회로도 위치를 특정할 근거를 찾지 못했다. 추측으로 채우지 않는다(§6).

COMMIT;


