-- 3. 실행 후 검증 — 위 24건이 의도한 값으로 반영됐는지, 나머지(율치 등)는
--    그대로 NULL인지 확인
-- ─────────────────────────────────────────────────────────────────────────
SELECT plant_id, plant_name, operator, lat, lon,
       CASE WHEN lat IS NULL THEN '좌표없음' ELSE '좌표있음' END AS status
FROM plants
WHERE fuel_type = 'solar'
ORDER BY plant_id;

-- 좌표 없는 태양광이 정확히 1기(율치, plant_id=143)만 남아야 한다.
SELECT count(*) AS 좌표없는_태양광_기수
FROM plants WHERE fuel_type = 'solar' AND lat IS NULL;
-- 기대값: 1


