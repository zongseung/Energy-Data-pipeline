SELECT plant_id, plant_name, operator, lat, lon, address
FROM plants
WHERE plant_id IN (
    -- 기존 값 정정 (6)
    33, 26, 4, 11, 2, 25,
    -- 신규 채움 (18)
    9, 8, 1, 12, 10, 13,      -- 신인천 계열
