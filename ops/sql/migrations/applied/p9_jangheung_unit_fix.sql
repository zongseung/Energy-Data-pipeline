-- P9-14: 서부 장흥풍력 단위 교정 Wh -> kWh (2026-10-21)
--
-- 발견: P9-13 뒤 정격초과 검사에 13,200행이 남아 확인하다 나왔다.
-- 근거 — 같은 서부·같은 정격(18MW)의 화순풍력과 나란히 두면 명확하다:
--     장흥  평균 2,449,424  이용률 13,607.9%   ← 불가능
--     화순  평균     2,801  이용률     15.6%   ← 풍력 전형
--   1000 으로 나누면 장흥이 이용률 13.6% · 최대출력 85.1% 로 정상범위에 들어온다.
--   연도별 장흥/화순 배수가 773~1072 로 흔들리는 건 두 단지의 풍황이 달라서이고,
--   1000배라는 결론과 모순되지 않는다.
-- 원인: 2026-10-21 에 병합한 두 계열 중 '장흥 풍력 발전소'(구 plant_id 49) 쪽 일회성
--   load 가 Wh 로 적재된 것으로 보인다. 화순은 같은 로더인데 kWh 였다.
--
-- 되돌리기: data/backup/jangheung_before_unitfix_20261021.csv
BEGIN;
UPDATE generation g SET gen_kwh = g.gen_kwh / 1000.0
 FROM plants p
 WHERE g.plant_id = p.plant_id
   AND p.operator = 'seobu' AND p.plant_name = '장흥풍력';
COMMIT;
