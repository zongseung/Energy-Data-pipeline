-- P9-12: 남동 누적값 혼입 제거 (2026-10-21)
--
-- 발견 경로: P9-10 으로 thermal 을 쪼갠 뒤 v_generation_hourly 의 0시/23시 평균이 터져
--   원인을 좁히다 나왔다. 설비 24기 중 **영동_2 · 영흥_6 두 기의 2024년**만 문제였고,
--   연료·사업자 단위 문제가 아니었다.
--
-- 정체: 시간별 발전량이 아니라 **적산 계량값**이다. 시간이 갈수록 단조 증가한다 —
--   영흥_6 2024-07-08: 17시 1.56e9 → 20시 8.21e9 → 23시 9.34e9 → 익일 0시 9.34e9.
--   870MW 설비의 시간당 상한은 0.87e6 kWh 다. 1,000배 넘는다.
--
-- 판정 기준: **설비용량 × 1,000 × 1.5 초과** 로 걸러 130행이 나왔으나 그중 118행(분당 계열)은
--   정격의 1.5~15배로 누적값이 아니었다 — 분당 가스터빈은 호기 매핑이 '근사'다
--   (capacities.py 주석: "CG1~5=1블록 GT, CG6~8=2블록 GT 로 매핑(근사)").
--   실제 호기와 어긋나 정격을 넘어 보이는 것이므로 **복원했다**.
--   누적값이 확실한 **12행만 삭제한다** — 영흥_6 9행(최대 정격의 10,735배) · 영동_2 2행(19,324배)
--   · 영동_1 1행. 단조 증가 패턴과 1,000배 이상 초과가 함께 나타나는 것만 누적값으로 본다.
-- NULL 로 지우지 않고 **삭제**한다 — 이 시각의 참값을 알 방법이 없고, NULL 로 두면
--   "측정했으나 결측" 과 구분이 안 된다. 행이 없으면 "자료 없음" 이 분명하다.
--
-- 되돌리기: data/backup/namdong_cumulative_outliers_20261021.csv
BEGIN;
DELETE FROM generation g
 USING plants p
 WHERE g.plant_id = p.plant_id
   AND p.operator = 'namdong'
   AND p.capacity_mw IS NOT NULL
   AND g.gen_kwh > p.capacity_mw * 1000 * 20;   -- 정격의 20배 초과 = 누적값
COMMIT;
